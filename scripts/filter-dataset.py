#!/usr/bin/env python3
"""Create a filtered copy of a dataset by excluding rejected image stems.

Reads a reject list (one image stem per line, as emitted by audit-dataset.py)
and copies everything NOT in that list from <src> to <dst>. Captions + images
copied together. Pre-computed .npz latent caches left behind (regenerated by
next training run).

Usage:
  python3 scripts/filter-dataset.py \\
      ~/docker-volumes/training-data/datasets/sophia-curated \\
      ~/docker-volumes/training-data/datasets/sophia-clean \\
      --rejects /tmp/sophia-rejects-narrow.txt
"""
from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

COPY_EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp", ".txt"}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("src", help="source dataset directory")
    ap.add_argument("dst", help="destination directory (created if missing)")
    ap.add_argument("--rejects", required=True,
                    help="path to reject list (one stem per line)")
    ap.add_argument("--dry-run", action="store_true",
                    help="print what would happen, don't copy")
    args = ap.parse_args()

    src = Path(args.src)
    dst = Path(args.dst)
    if not src.is_dir():
        print(f"error: src {src} is not a directory", file=sys.stderr)
        return 1

    rejects = set()
    with open(args.rejects, encoding="utf-8") as fp:
        for line in fp:
            s = line.strip()
            if s:
                rejects.add(s)

    print(f"Source:    {src}  ({len(list(src.iterdir()))} entries)")
    print(f"Destination: {dst}")
    print(f"Rejects:   {len(rejects)} stems")

    if not args.dry_run:
        dst.mkdir(parents=True, exist_ok=True)

    copied_imgs = 0
    copied_caps = 0
    skipped = 0

    # Iterate all files; skip any whose stem is in reject list
    for f in sorted(src.iterdir()):
        if not f.is_file():
            continue
        if f.suffix.lower() not in COPY_EXTENSIONS:
            continue
        if f.stem in rejects:
            skipped += 1
            continue
        if not args.dry_run:
            shutil.copy2(f, dst / f.name)
        if f.suffix.lower() == ".txt":
            copied_caps += 1
        else:
            copied_imgs += 1

    print()
    print(f"Copied:  {copied_imgs} images, {copied_caps} captions")
    print(f"Skipped: {skipped} files (matched reject list)")
    if args.dry_run:
        print("(dry run — nothing written)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
